def validate_locale(language: object) -> str:
    """Validate an exact, case-sensitive supported BCP 47 locale."""
    if not isinstance(language, str) or language not in SUPPORTED_LOCALES:
        received = repr(language)
        raise ConfigurationError(
            f"Locale não suportado recebido de /system-settings: {received}. "
            "Informe exatamente um destes locales: "
            + ", ".join(SUPPORTED_LOCALES)
        )
    return language


def _system_settings_endpoint(url: str | None = None) -> str:
    base_url = (
        url
        or os.getenv("SYSTEM_SETTINGS_URL", "").strip()
        or os.getenv("KUBEOPTIX_SYSTEM_SETTINGS_URL", "").strip()
        or SYSTEM_SETTINGS_BASE_URL
    ).rstrip("/")
    if base_url.endswith(SYSTEM_SETTINGS_PATH):
        return base_url
    return f"{base_url}{SYSTEM_SETTINGS_PATH}"


def resolve_system_locale(*, url: str | None = None, timeout: float = 5.0) -> str:
    """Read and validate the report locale from the system-settings service."""
    endpoint = _system_settings_endpoint(url)
    request = Request(endpoint, headers={"Accept": "application/json"})
    try:
        with urlopen(request, timeout=timeout) as response:
            payload = json.load(response)
    except HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace").strip()
        detail = f": {body}" if body else ""
        raise ConfigurationError(
            f"Falha ao consultar {endpoint} (HTTP {exc.code}){detail}"
        ) from exc
    except URLError as exc:
        raise ConfigurationError(
            f"Não foi possível acessar {endpoint}: {exc.reason}"
        ) from exc
    except (OSError, TimeoutError, json.JSONDecodeError) as exc:
        raise ConfigurationError(
            f"Não foi possível consultar {endpoint}: {exc}"
        ) from exc
    if not isinstance(payload, Mapping):
        raise ConfigurationError("Resposta de /system-settings inválida.")
    return validate_locale(payload.get("language"))


def babel_language(locale: str) -> str:
    return _BABEL_LANGUAGES[validate_locale(locale)]


def _replace_catalog_entry(content: str, source: str, target: str) -> str:
    pattern = re.escape(source)
    if source[0].isalnum():
        pattern = rf"(?<!\w){pattern}"
    if source[-1].isalnum():
        pattern = rf"{pattern}(?!\w)"
    return re.sub(pattern, lambda _: target, content)


def translate_report(content: str, locale: str) -> str:
    """Translate user-facing report fragments while preserving technical values."""
    locale = validate_locale(locale)
    for pattern, replacement in _PATTERN_TRANSLATIONS[locale]:
        content = re.sub(pattern, replacement, content)
    translations = _TRANSLATIONS[locale]
    for source, target in sorted(translations.items(), key=lambda item: len(item[0]), reverse=True):
        content = _replace_catalog_entry(content, source, target)
    return content
